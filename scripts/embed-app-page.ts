import { readFileSync, writeFileSync } from 'node:fs';

// Vercel serves public/ from its CDN, so the file is not on the serverless
// function's filesystem. Embed the built shell into the server bundle instead.
// The hashed script and style it references are still served as static assets.
for (const [file, target, name] of [['public/app.html', 'src/app-html.ts', 'appHtml'], ['public/site.html', 'src/site-html.ts', 'siteHtml']] as const) {
  const html = readFileSync(file, 'utf8');
  writeFileSync(target, `// Generated by scripts/embed-app-page.ts during npm run build. Do not edit.\nexport const ${name} = ${JSON.stringify(html)};\n`);
  console.log(`Embedded ${file} (${html.length} bytes) into ${target}`);
}
